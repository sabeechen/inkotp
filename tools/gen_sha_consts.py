#!/usr/bin/env python3
"""Generate lib/otpcore/sha_consts.inc.

The SHA-2 round constants and initial values are the fractional parts of the
cube and square roots of the first primes (FIPS 180-4). Deriving them here
avoids hand-copied tables; the host tests check the result against published
digests.
"""
from math import isqrt
from pathlib import Path


def primes(n):
    found = []
    candidate = 2
    while len(found) < n:
        if all(candidate % p for p in found):
            found.append(candidate)
        candidate += 1
    return found


def icbrt(n):
    lo, hi = 0, 1 << ((n.bit_length() + 2) // 3 + 1)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** 3 <= n:
            lo = mid
        else:
            hi = mid - 1
    return lo


def table(name, ctype, values, width, per_line):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    suffix = "ULL" if width == 16 else "UL"
    for i in range(0, len(values), per_line):
        row = ", ".join(f"0x{v:0{width}x}{suffix}" for v in values[i:i + per_line])
        lines.append(f"    {row},")
    lines.append("};")
    return "\n".join(lines)


p = primes(80)
out = [
    "// Generated by tools/gen_sha_consts.py - do not edit.",
    table("kSha256K", "uint32_t", [icbrt(x << 96) & 0xFFFFFFFF for x in p[:64]], 8, 6),
    table("kSha256Init", "uint32_t", [isqrt(x << 64) & 0xFFFFFFFF for x in p[:8]], 8, 4),
    table("kSha512K", "uint64_t", [icbrt(x << 192) & (2**64 - 1) for x in p], 16, 3),
    table("kSha512Init", "uint64_t", [isqrt(x << 128) & (2**64 - 1) for x in p[:8]], 16, 2),
]
target = Path(__file__).resolve().parent.parent / "lib" / "otpcore" / "sha_consts.inc"
target.write_text("\n\n".join(out) + "\n")
print(f"wrote {target}")
